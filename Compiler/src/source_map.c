#include "source_map.h"
#include "array.h"

/* 快照只保存各次插入的文本。片段表表示当前文本中各段对应的快照及字节起点。 */
typedef struct {
    size_t id, start, length;
} Piece;
typedef struct {
    AtriSource source;
    Piece parent;
} Snapshot;
struct AtriSourceMap {
    Snapshot *sources;
    size_t count, capacity;
    Piece *pieces;
    size_t piece_count;
};

static char *duplicate(const char *bytes, size_t length) {
    char *out = malloc(length + 1);
    if (out) {
        memcpy(out, bytes, length);
        out[length] = 0;
    }
    return out;
}

static Piece locate(const AtriSourceMap *map, size_t at) {
    size_t offset = 0;
    for (size_t i = 0; i < map->piece_count; ++i) {
        Piece p = map->pieces[i];
        if (at < offset + p.length || i + 1 == map->piece_count) {
            size_t skip = at - offset < p.length ? at - offset : p.length;
            return (Piece){p.id, p.start + skip, p.length - skip};
        }
        offset += p.length;
    }
    return (Piece){0};
}

static void slice(const AtriSourceMap *map, Piece *out, size_t *count, size_t from, size_t to) {
    size_t at = 0;
    for (size_t i = 0; i < map->piece_count && at < to; ++i) {
        Piece p = map->pieces[i];
        size_t left = from > at ? from : at, right = at + p.length < to ? at + p.length : to;
        if (left < right) {
            out[(*count)++] = (Piece){p.id, p.start + left - at, right - left};
        }
        at += p.length;
    }
}

void atri_source_map_destroy(AtriSourceMap *map) {
    if (!map) {
        return;
    }
    for (size_t i = 0; i < map->count; ++i) {
        free((char *)map->sources[i].source.name);
        free((char *)map->sources[i].source.text);
    }
    free(map->sources);
    free(map->pieces);
    free(map);
}

bool atri_source_edit(AtriSource *s, AtriSourceMap **owner, AtriSpan range, AtriSpan origin, const char *text,
                      size_t length, const char *producer) {
    size_t base = s->length - (range.end - range.start);
    if (length >= SIZE_MAX - base) {
        return false;
    }
    AtriSourceMap *m = *owner;
    if (!m) {
        m = calloc(1, sizeof(*m));
        if (!m) {
            return false;
        }
        Snapshot first = {{duplicate(s->name, strlen(s->name)), duplicate(s->text, s->length), s->length}, {0}};
        m->pieces = malloc(sizeof(*m->pieces));
        if (!first.source.name || !first.source.text || !m->pieces ||
            !atri_append((void **)&m->sources, &m->count, &m->capacity, sizeof(first), &first)) {
            free((char *)first.source.name);
            free((char *)first.source.text);
            atri_source_map_destroy(m);
            return false;
        }
        m->pieces[m->piece_count++] = (Piece){0, 0, s->length};
        *owner = m;
    }
    char *name = malloc(strlen(producer) + sizeof("<generated by >"));
    if (name) {
        sprintf(name, "<generated by %s>", producer);
    }
    Piece parent = locate(m, origin.start);
    if (parent.length > origin.end - origin.start) {
        parent.length = origin.end - origin.start;
    }
    Snapshot generated = {{name, duplicate(text, length), length}, parent};
    char *expanded = malloc(base + length + 1);
    Piece *pieces = calloc(m->piece_count + 3, sizeof(*pieces));
    if (!expanded || !pieces || !name || !generated.source.text ||
        !atri_append((void **)&m->sources, &m->count, &m->capacity, sizeof(generated), &generated)) {
        free(name);
        free((char *)generated.source.text);
        free(expanded);
        free(pieces);
        return false;
    }
    size_t count = 0;
    slice(m, pieces, &count, 0, range.start);
    if (length) {
        pieces[count++] = (Piece){m->count - 1, 0, length};
    }
    slice(m, pieces, &count, range.end, s->length);
    memcpy(expanded, s->text, range.start);
    memcpy(expanded + range.start, text, length);
    memcpy(expanded + range.start + length, s->text + range.end, s->length - range.end);
    expanded[base + length] = 0;
    free(m->pieces);
    m->piece_count = count;
    m->pieces = pieces;
    free((char *)s->text);
    s->text = expanded;
    s->length = base + length;
    return true;
}

void atri_source_label(FILE *stream, const AtriSourceMap *m, AtriSource source, AtriSpan span, const char *level,
                       const char *message, const char *detail) {
    if (!m) {
        atri_print_label(stream, source, span, level, message, detail);
        return;
    }
    Piece p = locate(m, span.start);
    size_t width = span.end - span.start;
    if (p.length > width) {
        p.length = width;
    }
    atri_print_label(stream, m->sources[p.id].source, (AtriSpan){p.start, p.start + p.length}, level, message,
                     detail);
    if (width > p.length && span.end <= source.length) {
        Piece tail = locate(m, span.end - 1);
        atri_print_label(stream, m->sources[tail.id].source, (AtriSpan){tail.start, tail.start + 1}, "note",
                         "range ends in this source fragment", "");
    }
    size_t depth = 0;
    while (p.id) {
        p = m->sources[p.id].parent;
        ++depth;
        if (depth > 6 && p.id) { continue; }
        if (depth > 7) { fprintf(stream, "note: skipped %zu intermediate source expansions\n", depth - 7); }
        atri_print_label(stream, m->sources[p.id].source, (AtriSpan){p.start, p.start + p.length}, "note",
                         "expanded or rewritten here", "");
    }
}
