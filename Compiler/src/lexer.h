#ifndef ATRI_LEXER_H
#define ATRI_LEXER_H

#include "frontend.h"

typedef enum {
    ATRI_TOKEN_EOF,
    ATRI_TOKEN_ERROR,
    ATRI_TOKEN_STRUCT, ATRI_TOKEN_DOT, ATRI_TOKEN_FN, ATRI_TOKEN_IMPORT, ATRI_TOKEN_EXPORT, ATRI_TOKEN_SCOPE,
    ATRI_TOKEN_RETURN,
    ATRI_TOKEN_NULL,
    ATRI_TOKEN_TRUE, ATRI_TOKEN_FALSE, ATRI_TOKEN_IF, ATRI_TOKEN_ELSE,
    ATRI_TOKEN_WHILE, ATRI_TOKEN_DO, ATRI_TOKEN_FOR, ATRI_TOKEN_LOOP,
    ATRI_TOKEN_BREAK, ATRI_TOKEN_CONTINUE,
    ATRI_TOKEN_IDENTIFIER,
    ATRI_TOKEN_INTEGER,
    ATRI_TOKEN_STRING,
    ATRI_TOKEN_ATTRIBUTE_OPEN, ATRI_TOKEN_ATTRIBUTE_CLOSE,
    ATRI_TOKEN_LEFT_PAREN,
    ATRI_TOKEN_RIGHT_PAREN,
    ATRI_TOKEN_LEFT_BRACE,
    ATRI_TOKEN_RIGHT_BRACE,
    ATRI_TOKEN_ARROW,
    ATRI_TOKEN_SEMICOLON,
    ATRI_TOKEN_COLON, ATRI_TOKEN_CONSTANT_INIT, ATRI_TOKEN_COMMA, ATRI_TOKEN_EQUAL,
    ATRI_TOKEN_PLUS, ATRI_TOKEN_MINUS, ATRI_TOKEN_STAR,
    ATRI_TOKEN_SLASH, ATRI_TOKEN_PERCENT, ATRI_TOKEN_AMPERSAND,
    ATRI_TOKEN_EQ, ATRI_TOKEN_NE, ATRI_TOKEN_LT, ATRI_TOKEN_LE,
    ATRI_TOKEN_GT, ATRI_TOKEN_GE, ATRI_TOKEN_NOT, ATRI_TOKEN_AND, ATRI_TOKEN_OR
} AtriTokenKind;

typedef struct {
    AtriTokenKind kind;
    AtriSpan span;
} AtriToken;

typedef struct {
    AtriSource source;
    size_t offset;
} AtriLexer;

AtriLexer atri_lexer_create(AtriSource source);
AtriToken atri_lexer_next(AtriLexer *lexer, AtriDiagnostic *diagnostic);

#endif
